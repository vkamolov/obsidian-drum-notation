import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { loadBundledTsModule } from "./load-ts-module.mjs";
import { REFERENCE_ROOT, REPO_ROOT } from "./plugin-paths.mjs";

const check = process.argv.includes("--check");
const module = await loadBundledTsModule(
  'export { DRUM_KIT as default } from "./src/kit.ts";',
  REPO_ROOT
);
const kit = module.default;
if (!Array.isArray(kit) || kit.length === 0) {
  throw new Error("DRUM_KIT did not produce an instrument array");
}

const output = `# Drum kit reference

Generated from \`src/kit.ts\`. Do not edit this file manually.

\`\`\`json
${JSON.stringify(kit, null, 2)}
\`\`\`
`;
const destination = path.join(REFERENCE_ROOT, "kit-reference.md");

if (check) {
  const current = await readFile(destination, "utf8").catch(() => "");
  if (current !== output) {
    throw new Error("kit-reference.md is stale; run npm run agent-plugin:generate");
  }
  console.log(`Kit reference matches ${kit.length} instruments.`);
} else {
  await writeFile(destination, output);
  console.log(`Generated kit reference for ${kit.length} instruments.`);
}
